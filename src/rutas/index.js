const router = require('express').Router();
const c = require('../controladores/inventario');
const ventas = require('../controladores/ventas');
const proveedores = require('../controladores/proveedores');
const compras = require('../controladores/compras');
const servicios = require('../controladores/servicios');
router.get('/', c.pagina);
router.get(['/productos','/inventario'], c.pagina);
router.get('/productos/nuevo', c.formulario);
router.post('/productos', c.guardar);
router.param('id', (req,res,next,id) => /^\d{1,10}$/.test(id) ? next() : res.sendStatus(404));
router.get('/servicios',servicios.lista);
router.get('/servicios/nuevo',servicios.formulario);
router.post('/servicios',servicios.guardar);
router.get('/servicios/:id/editar',servicios.formulario);
router.post('/servicios/:id',servicios.guardar);
router.post('/servicios/:id/estado',servicios.estado);
router.get('/pendiente/servicios',(req,res)=>res.redirect('/servicios'));
router.get('/proveedores',proveedores.lista);
router.get('/proveedores/nuevo',proveedores.formulario);
router.post('/proveedores',proveedores.guardar);
router.get('/proveedores/:id/editar',proveedores.formulario);
router.post('/proveedores/:id',proveedores.guardar);
router.post('/proveedores/:id/desactivar',proveedores.desactivar);
router.get('/compras',compras.historial);
router.get('/compras/nueva',compras.nueva);
router.get('/compras/productos',compras.buscar);
router.post('/compras',compras.guardar);
router.get('/compras/:id',compras.detalle);
router.get('/pendiente/proveedores',(req,res)=>res.redirect('/proveedores'));
router.get('/pendiente/compras',(req,res)=>res.redirect('/compras'));
router.get('/ventas/nueva',ventas.nueva);
router.get('/ventas/productos',ventas.buscar);
router.get('/ventas/servicios',ventas.buscarServicios);
router.get('/ventas',ventas.historial);
router.post('/ventas',ventas.guardar);
router.get('/ventas/:id',ventas.detalle);
router.get('/pendiente/ventas',(req,res)=>res.redirect('/ventas/nueva'));
router.get('/pendiente/historial',(req,res)=>res.redirect('/ventas'));
router.get('/productos/:id/editar', c.formulario);
router.get('/productos/:id', c.detalle);
router.post('/productos/:id', c.guardar);
router.post('/productos/:id/desactivar', c.desactivar);
router.get('/categorias', (req,res) => c.categorias(req,res));
router.get('/categorias/:id/editar', c.editarCategoria);
router.post('/categorias', c.guardarCategoria);
router.post('/categorias/:id', c.guardarCategoria);
const pendientes = { ventas:'Ventas', caja:'Caja y gastos', clientes:'Clientes', proveedores:'Proveedores', compras:'Compras', reportes:'Reportes', configuracion:'Configuración', usuarios:'Usuarios', movimientos:'Movimientos', servicios:'Servicios', historial:'Historial' };
router.get('/pendiente/:seccion', (req,res,next) => {
  const titulo = pendientes[req.params.seccion];
  if (!titulo) return next();
  res.render('mensaje', { titulo, mensaje: 'Pendiente de implementación. Esta entrega permite gestionar productos, categorías y consultar existencias. Aquí todavía no se registran operaciones.' });
});
module.exports = router;
